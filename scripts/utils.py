def write_pdb_from_coords(
    coords: np.ndarray,
    atom_names: list[str],
    residue_names: list[str],
    residue_ids: list[int],
    chain_ids: list[str],
    output_path: str,
    elements: Optional[list[str]] = None,
):
    """Write a minimal PDB file from coordinate arrays."""
    with open(output_path, "w") as f:
        f.write("REMARK   Generated by prompt-conditioned frozen-AF3 D-protein study\n")
        for i, (xyz, aname, rname, rid, cid) in enumerate(
            zip(coords, atom_names, residue_names, residue_ids, chain_ids)
        ):
            elem = elements[i] if elements else aname[0]
            f.write(
                f"ATOM  {i+1:5d} {aname:<4s} {rname:>3s} {cid:1s}{rid:4d}    "
                f"{xyz[0]:8.3f}{xyz[1]:8.3f}{xyz[2]:8.3f}"
                f"  1.00  0.00          {elem:>2s}\n"
            )
        f.write("END\n")


def parse_pdb_ca_coords(pdb_path: str) -> tuple[np.ndarray, list[int], list[str]]:
    """Extract C-alpha coordinates, residue IDs, and chain IDs from a PDB file."""
    coords = []
    res_ids = []
    chain_ids = []
    with open(pdb_path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            if line.startswith(("ATOM", "HETATM")):
                atom_name = line[12:16].strip()
                if atom_name == "CA":
                    x = float(line[30:38])
                    y = float(line[38:46])
                    z = float(line[46:54])
                    coords.append([x, y, z])
                    res_ids.append(int(line[22:26]))
                    chain_ids.append(line[21])
    return np.array(coords), res_ids, chain_ids


def parse_pdb_all_atoms(pdb_path: str) -> list[dict]:
    """Parse all atoms from a PDB file."""
    atoms = []
    with open(pdb_path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            if line.startswith(("ATOM", "HETATM")):
                atoms.append({
                    "serial": int(line[6:11]),
                    "name": line[12:16].strip(),
                    "resname": line[17:20].strip(),
                    "chain": line[21],
                    "resid": int(line[22:26]),
                    "x": float(line[30:38]),
                    "y": float(line[38:46]),
                    "z": float(line[46:54]),
                    "occupancy": float(line[54:60]) if len(line) > 60 else 1.0,
                    "bfactor": float(line[60:66]) if len(line) > 66 else 0.0,
                    "element": line[76:78].strip() if len(line) > 78 else line[12:14].strip()[0],
                })
    return atoms


def backbone_atoms_for_residue(atoms: list[dict], chain: str, resid: int) -> dict:
    """Get N, CA, C, O coordinates for a specific residue."""
    result = {}
    for a in atoms:
        if a["chain"] == chain and a["resid"] == resid and a["name"] in ("N", "CA", "C", "O"):
            result[a["name"]] = np.array([a["x"], a["y"], a["z"]])
    return result


def compute_dihedral(p1, p2, p3, p4):
    """Compute dihedral angle between four points in degrees."""
    b1 = p2 - p1
    b2 = p3 - p2
    b3 = p4 - p3
    n1 = np.cross(b1, b2)
    n2 = np.cross(b2, b3)
    n1_norm = np.linalg.norm(n1)
    n2_norm = np.linalg.norm(n2)
    if n1_norm < 1e-10 or n2_norm < 1e-10:
        return 0.0
    n1 = n1 / n1_norm
    n2 = n2 / n2_norm
    m = np.cross(n1, b2 / np.linalg.norm(b2))
    x = np.dot(n1, n2)
    y = np.dot(m, n2)
    return np.degrees(np.arctan2(y, x))


def compute_phi_psi(atoms: list[dict], chain: str, resid: int) -> tuple[Optional[float], Optional[float]]:
    """Compute phi and psi angles for a residue."""
    prev_bb = backbone_atoms_for_residue(atoms, chain, resid - 1)
    curr_bb = backbone_atoms_for_residue(atoms, chain, resid)
    next_bb = backbone_atoms_for_residue(atoms, chain, resid + 1)

    phi = None
    psi = None
    if "C" in prev_bb and all(k in curr_bb for k in ("N", "CA", "C")):
        phi = compute_dihedral(prev_bb["C"], curr_bb["N"], curr_bb["CA"], curr_bb["C"])
    if all(k in curr_bb for k in ("N", "CA", "C")) and "N" in next_bb:
        psi = compute_dihedral(curr_bb["N"], curr_bb["CA"], curr_bb["C"], next_bb["N"])
    return phi, psi


def rmsd(coords1: np.ndarray, coords2: np.ndarray) -> float:
    """Compute RMSD between two coordinate sets of same length."""
    assert coords1.shape == coords2.shape, f"Shape mismatch: {coords1.shape} vs {coords2.shape}"
    diff = coords1 - coords2
    return float(np.sqrt(np.mean(np.sum(diff**2, axis=-1))))


def kabsch_rmsd(coords1: np.ndarray, coords2: np.ndarray) -> float:
    """Compute RMSD after optimal superposition (Kabsch algorithm)."""
    c1 = coords1 - coords1.mean(axis=0)
    c2 = coords2 - coords2.mean(axis=0)

    H = c1.T @ c2
    U, S, Vt = np.linalg.svd(H)

    d = np.linalg.det(Vt.T @ U.T)
    sign_matrix = np.diag([1.0, 1.0, np.sign(d)])
    R = Vt.T @ sign_matrix @ U.T

    c1_rotated = c1 @ R.T
    return rmsd(c1_rotated, c2)


def mirror_coords(coords: np.ndarray, axis: str = "x") -> np.ndarray:
    """Reflect coordinates through a plane perpendicular to the given axis."""
    result = coords.copy()
    axis_idx = {"x": 0, "y": 1, "z": 2}[axis]
    result[:, axis_idx] = -result[:, axis_idx]
    return result


def save_metrics_csv(metrics_list: list[dict], output_path: str):
    if not metrics_list:
        return
    fieldnames = list(metrics_list[0].keys())
    for m in metrics_list[1:]:
        for k in m:
            if k not in fieldnames:
                fieldnames.append(k)
    with open(output_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(metrics_list)
