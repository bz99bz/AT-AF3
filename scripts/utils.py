def load_cases(config_path: Optional[str] = None) -> list[dict]:
    if config_path is None:
        config_path = str(CONFIGS_DIR / "at_af_7.json")
    with open(config_path, "r", encoding="utf-8-sig") as f:
        data = json.load(f)
